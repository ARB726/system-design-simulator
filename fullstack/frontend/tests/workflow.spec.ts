import { test, expect } from '@playwright/test';

test('register, simulate, compare, export, and inspect responsive layout',async({page})=>{
  await page.goto('/#sandbox');
  await expect(page.getByRole('heading',{name:'Your architecture. Under pressure.'})).toBeVisible();
  await page.screenshot({path:'../../.local/fullstack-desktop.png',fullPage:true});
  await page.getByLabel('Experiment name',{exact:true}).fill('Browser baseline');
  await page.getByRole('button',{name:'Sign in to run simulation',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Email',{exact:true}).fill(`browser-${Date.now()}@example.com`);
  await dialog.getByLabel('Password',{exact:true}).fill('correct-horse-battery-staple');
  await dialog.getByRole('button',{name:'Create local account'}).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button',{name:'Run simulation',exact:true}).click();
  await expect(page.getByText('Successful throughput',{exact:true})).toBeVisible({timeout:60000});
  await page.screenshot({path:'../../.local/fullstack-results.png',fullPage:true});
  await page.getByLabel('Experiment name',{exact:true}).fill('Browser candidate');
  await page.getByLabel('DB connections',{exact:true}).fill('32');
  await page.getByRole('button',{name:'Run simulation',exact:true}).click();
  await expect(page.getByText('Successful throughput',{exact:true})).toBeVisible({timeout:60000});
  await page.getByRole('button',{name:/Experiment library/}).click();
  await expect(page.getByRole('checkbox',{name:'Compare Browser candidate'})).toBeVisible();
  await page.getByRole('checkbox',{name:'Compare Browser baseline'}).check();
  await page.getByRole('checkbox',{name:'Compare Browser candidate'}).check();
  await page.getByRole('button',{name:'Compare designs',exact:true}).last().click();
  await expect(page.getByText(/Matched workload, seed, and chaos events/)).toBeVisible();
  await expect(page.getByRole('heading',{name:'Browser baseline'})).toBeVisible();
  await page.getByRole('button',{name:/Experiment library/}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export all'}).click();
  const archive=await download;
  expect(archive.suggestedFilename()).toBe('systems-lab-experiments.json');
  const archivePath=test.info().outputPath('experiments.json');
  await archive.saveAs(archivePath);
  await page.getByLabel('Experiment archive',{exact:true}).setInputFiles(archivePath);
  await expect(page.locator('.library-row')).toHaveCount(4);
  await page.getByRole('button',{name:'Learning lab'}).click();
  await expect(page.getByRole('button',{name:/Take on the challenge/})).toHaveCount(6);
  await page.getByRole('button',{name:'Sandbox',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('heading',{name:'Your architecture. Under pressure.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'../../.local/fullstack-mobile.png',fullPage:true});
});
